--- Give a player an item. Returns false when it did not fit.
---@return boolean
function PrinterInventory.AddItem(src, item, count, metadata)
    count = count or 1

    local own = customFn('AddItem')
    if own then
        local fine, done = pcall(own, src, item, count, metadata)
        return (fine and done) and true or false
    end

    local inv = PrinterInventory.name
    local ok, done = true, false

    if inv == 'ox' then
        ok = pcall(function()
            done = exports.ox_inventory:AddItem(src, item, count, metadata) and true or false
        end)

    elseif inv == 'origen' then
        ok = pcall(function()
            done = exports.origen_inventory:AddItem(src, item, count, nil, metadata) ~= false
        end)

    elseif inv == 'tgiann' then
        ok = pcall(function()
            done = exports['tgiann-inventory']:AddItem(src, item, count, nil, metadata) ~= false
        end)

    elseif inv == 'qs' then
        ok = pcall(function()
            done = exports['qs-inventory']:AddItem(src, item, count, nil, metadata) ~= false
        end)

    elseif inv == 'ak47' then
        -- qb-shaped: (inv, item, amount, slot, info). Returns (bool, reason).
        ok = pcall(function()
            done = exports.ak47_inventory:AddItem(src, item, count, nil, metadata) ~= false
        end)
        -- Its export refused (or is not there on this build): ak47 keeps the
        -- qb-core player object in sync, so the framework's own AddItem is a
        -- genuinely different route to the same inventory. Only ever tried
        -- AFTER a refusal, so nothing can be handed over twice.
        if not done then
            local p = fwPlayer(src)
            if p and p.Functions and p.Functions.AddItem then
                pcall(function()
                    done = p.Functions.AddItem(item, count, nil, metadata) and true or false
                end)
            end
        end

    elseif inv == 'codem' then
        ok = pcall(function()
            done = exports['codem-inventory']:AddItem(src, item, count, nil, metadata) ~= false
        end)

    elseif inv == 'core' then
        ok = pcall(function()
            exports.core_inventory:addItem(src, 'default', item, count, metadata)
            done = true
        end)

    elseif inv == 'qb' then
        local p = fwPlayer(src)
        if p and p.Functions then
            ok = pcall(function()
                done = p.Functions.AddItem(item, count, nil, metadata) and true or false
            end)
        end

    elseif inv == 'esx' then
        local p = fwPlayer(src)
        if p then
            ok = pcall(function()
                if p.canCarryItem and not p.canCarryItem(item, count) then
                    done = false
                    return
                end
                p.addInventoryItem(item, count)
                done = true
            end)
        end
    end

    return ok and done or false
end

--- Take an item away. Returns false when the player did not have it.
---@return boolean
function PrinterInventory.RemoveItem(src, item, count, metadata)
    count = count or 1

    local own = customFn('RemoveItem')
    if own then
        local fine, done = pcall(own, src, item, count, metadata)
        return (fine and done) and true or false
    end

    local inv = PrinterInventory.name
    local ok, done = true, false

    if inv == 'ox' then
        ok = pcall(function()
            done = exports.ox_inventory:RemoveItem(src, item, count, metadata) and true or false
        end)

    elseif inv == 'origen' then
        ok = pcall(function()
            done = exports.origen_inventory:RemoveItem(src, item, count) ~= false
        end)

    elseif inv == 'tgiann' then
        ok = pcall(function()
            done = exports['tgiann-inventory']:RemoveItem(src, item, count) ~= false
        end)

    elseif inv == 'qs' then
        ok = pcall(function()
            done = exports['qs-inventory']:RemoveItem(src, item, count) ~= false
        end)

    elseif inv == 'ak47' then
        ok = pcall(function()
            done = exports.ak47_inventory:RemoveItem(src, item, count) ~= false
        end)

    elseif inv == 'codem' then
        ok = pcall(function()
            done = exports['codem-inventory']:RemoveItem(src, item, count) ~= false
        end)

    elseif inv == 'core' then
        ok = pcall(function()
            exports.core_inventory:removeItem(src, 'default', item, count)
            done = true
        end)

    elseif inv == 'qb' then
        local p = fwPlayer(src)
        if p and p.Functions then
            ok = pcall(function()
                done = p.Functions.RemoveItem(item, count) and true or false
            end)
        end

    elseif inv == 'esx' then
        local p = fwPlayer(src)
        if p then
            ok = pcall(function()
                if p.getInventoryItem(item).count < count then
                    done = false
                    return
                end
                p.removeInventoryItem(item, count)
                done = true
            end)
        end
    end

    return ok and done or false
end

-- ---------------------------------------------------------------------------
-- Room to carry
--
-- Asked before anything is handed over, so a finished print is never destroyed
-- because a bag was full. An inventory that cannot answer is assumed to have
-- room -- AddItem is checked anyway, so nothing is lost either way.
-- ---------------------------------------------------------------------------

---@return boolean
function PrinterInventory.CanCarry(src, item, count)
    count = count or 1

    local own = customFn('CanCarry')
    if own then
        -- Fails OPEN: an override that errors must never be the reason a
        -- finished print is refused. AddItem is checked anyway.
        local fine, room = pcall(own, src, item, count)
        if not fine then return true end
        return room and true or false
    end

    local inv = PrinterInventory.name
    local room = true

    if inv == 'ox' then
        pcall(function()
            room = exports.ox_inventory:CanCarryItem(src, item, count) and true or false
        end)

    elseif inv == 'origen' then
        pcall(function()
            room = exports.origen_inventory:CanCarryItem(src, item, count) ~= false
        end)

    elseif inv == 'tgiann' then
        pcall(function()
            room = exports['tgiann-inventory']:CanCarryItem(src, item, count) ~= false
        end)

    elseif inv == 'ak47' then
        -- CanAddItem is the qb-shaped name; CanCarryItem the ox alias.
        local answered = false
        pcall(function()
            room = exports.ak47_inventory:CanAddItem(src, item, count) ~= false
            answered = true
        end)
        if not answered then
            pcall(function()
                room = exports.ak47_inventory:CanCarryItem(src, item, count) ~= false
            end)
        end

    elseif inv == 'qs' then
        pcall(function()
            room = exports['qs-inventory']:CanCarryItem(src, item, count) ~= false
        end)

    elseif inv == 'qb' then
        if running('qb-inventory') then
            pcall(function()
                room = exports['qb-inventory']:CanAddItem(src, item, count) and true or false
            end)
        end

    elseif inv == 'esx' then
        local p = fwPlayer(src)
        if p and p.canCarryItem then
            pcall(function() room = p.canCarryItem(item, count) and true or false end)
        end
    end

    return room
end

-- ---------------------------------------------------------------------------
-- Is this item registered in the inventory at all?
--
-- The single most common "it does not work" on a fresh install: the item was
-- pasted into one items list while the inventory actually in use reads a
-- different one. ak47_inventory, tgiann and qs all ship their own, so a server
-- that followed the qb-core instructions ends up with an inventory that has
-- never heard of `3dprinter`.
--
-- Every qb-shaped AddItem answers an unknown item with a plain `false` -- the
-- exact same answer it gives for a full bag. That is why a player with 80 kg
-- free was being told they had no space. Asking this first lets the resource
-- say what is really wrong.
--
---@return boolean|nil known  true / false, or nil when nothing could answer
function PrinterInventory.ItemExists(item)
    if type(item) ~= 'string' or item == '' then return nil end
    local key   = item:lower()
    local known = nil

    -- Each probe either answers (true/false) or declines (nil / an error).
    local function ask(fn)
        if known ~= nil then return end
        local fine, res = pcall(fn)
        if fine and res ~= nil then known = res and true or false end
    end

    local inv = PrinterInventory.name

    if inv == 'ox' then
        ask(function() return exports.ox_inventory:Items(item) ~= nil end)
        ask(function()
            local all = exports.ox_inventory:Items()
            if type(all) ~= 'table' then return nil end
            return all[item] ~= nil or all[key] ~= nil
        end)

    elseif inv == 'ak47' then
        ask(function()
            local all = exports.ak47_inventory:GetItemList()
            if type(all) ~= 'table' then return nil end
            return all[item] ~= nil or all[key] ~= nil
        end)
        ask(function()
            local all = exports.ak47_inventory:Items()
            if type(all) ~= 'table' then return nil end
            return all[item] ~= nil or all[key] ~= nil
        end)

    elseif inv == 'qs' then
        ask(function()
            local all = exports['qs-inventory']:GetItemList()
            if type(all) ~= 'table' then return nil end
            return all[item] ~= nil or all[key] ~= nil
        end)

    elseif inv == 'tgiann' then
        ask(function()
            local all = exports['tgiann-inventory']:GetItemList()
            if type(all) ~= 'table' then return nil end
            return all[item] ~= nil or all[key] ~= nil
        end)
    end

    -- The framework's shared list. Most qb-shaped inventories read it too, so
    -- it is a good answer even when the inventory itself could not be asked.
    ask(function()
        local core = exports['qb-core']:GetCoreObject()
        if type(core) ~= 'table' or type(core.Shared) ~= 'table'
            or type(core.Shared.Items) ~= 'table' then return nil end
        return core.Shared.Items[key] ~= nil or core.Shared.Items[item] ~= nil
    end)
    ask(function()
        local all = exports.qbx_core:GetItems()
        if type(all) ~= 'table' then return nil end
        return all[key] ~= nil or all[item] ~= nil
    end)
    ask(function()
        local core = exports['es_extended']:getSharedObject()
        if type(core) ~= 'table' then return nil end
        local all = core.Items or (core.GetItems and core.GetItems())
        if type(all) ~= 'table' then return nil end
        return all[key] ~= nil or all[item] ~= nil
    end)

    return known
end

--- Why did a give fail? Returns the locale key to show the player.
---
--- Handing back 'no_space' for everything sent owners hunting a weight problem
--- that was never there, so an item the inventory does not know is now named as
--- such -- on screen and, once per item, in the console where it can be acted on.
local warned = {}
---@return string localeKey
function PrinterInventory.WhyAddFailed(item)
    if PrinterInventory.ItemExists(item) ~= false then return 'no_space' end

    if not warned[item] then
        warned[item] = true
        print(('^1[rwprinter] The item "%s" is not registered in your inventory (%s). '
            .. 'Players cannot receive it until you add it to that inventory\'s own items '
            .. 'list -- see README.md. This is NOT a lack of space.^0')
            :format(item, PrinterInventory.name or 'unknown'))
    end

    return 'item_unknown'
end

