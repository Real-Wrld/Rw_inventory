--- Does the player have every material a recipe asks for?
---@return boolean ok, table|nil missing
function PrinterInventory.HasMaterials(src, materials)
    if not PrinterConfig.RequireMaterials then return true end

    local missing = {}

    for item, need in pairs(materials or {}) do
        local have = PrinterInventory.GetCount(src, item)
        if have < need then
            missing[#missing + 1] = { item = item, need = need, have = have }
        end
    end

    if #missing > 0 then return false, missing end
    return true
end

--- Take every material of a recipe.
---
--- If one of them fails halfway through, whatever was already taken is given
--- back. Without that, an inventory refusing the third material would leave
--- the player short of the first two with nothing to show for it.
---@return boolean
function PrinterInventory.TakeMaterials(src, materials)
    if not PrinterConfig.RequireMaterials then return true end

    local taken = {}

    for item, need in pairs(materials or {}) do
        if not PrinterInventory.RemoveItem(src, item, need) then
            for it, n in pairs(taken) do
                PrinterInventory.AddItem(src, it, n)
            end
            return false
        end

        taken[item] = need
    end

    return true
end

--- Give back a fraction of a recipe. Used when a job is cancelled.
function PrinterInventory.RefundMaterials(src, materials, ratio)
    ratio = ratio or 1.0
    if not PrinterConfig.RequireMaterials then return end

    for item, need in pairs(materials or {}) do
        local back = math.floor(need * ratio)
        if back > 0 then
            PrinterInventory.AddItem(src, item, back)
        end
    end
end

