

-- ---------------------------------------------------------------------------
-- PrinterInventory bridge
--
-- Every inventory operation in this resource is server-side and goes through
-- the `PrinterInventory` table below. Nothing else ever calls an inventory export
-- directly, so adding support for one that is not listed here means filling in
-- four functions and nothing else.
--
-- Supported out of the box:
--   ox_inventory · ak47_inventory · qb-inventory (and ps-inventory)
--   qs-inventory · codem-inventory · origen_inventory · tgiann-inventory
--   core_inventory
--   and the framework's own inventory (ESX / QBCore / Qbox)
--
-- `PrinterConfig.Inventory = 'auto'` picks one by looking at what is running.
--
-- YOUR OWN INVENTORY: do NOT edit this file. bridge/custom.lua is open in
-- both editions and its four functions override the ones here, one by one.
-- Set PrinterConfig.Inventory = 'custom' for an inventory that is not on the list at
-- all, or just define the one function your build answers differently.
-- ---------------------------------------------------------------------------

PrinterInventory = { name = nil }

local IS_SERVER = IsDuplicityVersion()

--- The four operations everything else is built out of.
local PRIMITIVES = { 'GetCount', 'AddItem', 'RemoveItem', 'CanCarry' }

local function running(name)
    return GetResourceState(name) == 'started'
end

--- Your implementation from bridge/custom.lua, when there is one.
---
--- Looked up per call rather than cached: the file is open in both editions,
--- so a server owner editing it and restarting the resource gets their change
--- without anything here having to be invalidated.
---@param name string one of PRIMITIVES
---@return function|nil
local function customFn(name)
    if type(CustomInventory) ~= 'table' then return nil end
    local fn = CustomInventory[name]
    return type(fn) == 'function' and fn or nil
end

-- ---------------------------------------------------------------------------
-- Detection
--
-- Order matters. The dedicated inventories come first, because most of them
-- also run alongside a framework whose own inventory would otherwise answer.
-- ---------------------------------------------------------------------------

local ORDER = {
    -- ak47_inventory leads: it ships an ox_inventory compat layer and can
    -- claim the ox_inventory RESOURCE name while the ox_inventory EXPORT name
    -- does not exist, so probing ox first would pick a backend that cannot
    -- answer.
    { res = 'ak47_inventory',   name = 'ak47' },
    { res = 'ox_inventory',     name = 'ox' },
    { res = 'origen_inventory', name = 'origen' },
    { res = 'tgiann-inventory', name = 'tgiann' },
    { res = 'qs-inventory',     name = 'qs' },
    { res = 'codem-inventory',  name = 'codem' },
    { res = 'core_inventory',   name = 'core' },
    { res = 'ps-inventory',     name = 'qb' },   -- a qb-inventory fork, same exports
    { res = 'qb-inventory',     name = 'qb' },
}

local function detect()
    local forced = PrinterConfig.Inventory

    if forced and forced ~= 'auto' then
        PrinterInventory.name = forced
    else
        for _, entry in ipairs(ORDER) do
            if running(entry.res) then
                PrinterInventory.name = entry.name
                break
            end
        end

        if not PrinterInventory.name then
            -- Nothing dedicated is running: fall back to whatever the
            -- framework carries.
            if PrinterFramework and PrinterFramework.name == 'esx' then
                PrinterInventory.name = 'esx'
            elseif PrinterFramework and (PrinterFramework.name == 'qb' or PrinterFramework.name == 'qbox') then
                PrinterInventory.name = 'qb'
            else
                PrinterInventory.name = 'ox'
            end
        end
    end

    print(('^2[rwprinter] PrinterInventory: %s^0'):format(PrinterInventory.name))

    -- What bridge/custom.lua takes over, if anything.
    local own = {}
    for _, fn in ipairs(PRIMITIVES) do
        if customFn(fn) then own[#own + 1] = fn end
    end

    if #own > 0 then
        print(('^2[rwprinter] bridge/custom.lua overrides: %s^0')
            :format(table.concat(own, ', ')))
    end

    -- 'custom' with a hole in it would fail silently at the worst possible
    -- moment -- a finished print with nowhere to go. Say it now instead.
    if PrinterInventory.name == 'custom' and #own < #PRIMITIVES then
        local missing = {}
        for _, fn in ipairs(PRIMITIVES) do
            if not customFn(fn) then missing[#missing + 1] = fn end
        end

        print("^1[rwprinter] PrinterConfig.Inventory = 'custom' but bridge/custom.lua^0")
        print(('^1[rwprinter] does not define: %s^0'):format(table.concat(missing, ', ')))
        print('^1[rwprinter] Printing will not work until they are filled in.^0')
    end
end

CreateThread(function()
    -- After the framework bridge, so the fallback above can see it.
    local tries = 0
    while not (PrinterFramework and PrinterFramework.name) and tries < 100 do
        Wait(100)
        tries = tries + 1
    end

    detect()
end)

if not IS_SERVER then return end

-- ---------------------------------------------------------------------------
-- The framework's own player object, for the inventories that need it.
-- ---------------------------------------------------------------------------

local function fwPlayer(src)
    return PrinterFramework and PrinterFramework.GetPlayer and PrinterFramework.GetPlayer(src) or nil
end

-- ---------------------------------------------------------------------------
-- How many of an item a player is carrying
-- ---------------------------------------------------------------------------

---@param src number
---@param item string
---@return number
function PrinterInventory.GetCount(src, item)
    local own = customFn('GetCount')
    if own then
        local ok, n = pcall(own, src, item)
        return (ok and tonumber(n)) or 0
    end

    local inv = PrinterInventory.name
    local n = 0

    if inv == 'ox' then
        pcall(function() n = exports.ox_inventory:GetItemCount(src, item) or 0 end)

    elseif inv == 'origen' then
        pcall(function() n = exports.origen_inventory:GetItemCount(src, item) or 0 end)

    elseif inv == 'tgiann' then
        pcall(function() n = exports['tgiann-inventory']:GetItemCount(src, item) or 0 end)

    elseif inv == 'qs' then
        pcall(function()
            local items = exports['qs-inventory']:GetInventory(src)
            for _, v in pairs(items or {}) do
                if v and v.name == item then n = n + (v.amount or v.count or 0) end
            end
        end)

    elseif inv == 'ak47' then
        -- ox-shaped alias first, then the native call, then the qb-shaped one.
        pcall(function() n = exports.ak47_inventory:GetItemCount(src, item) or 0 end)
        if (n or 0) == 0 then
            pcall(function() n = exports.ak47_inventory:GetAmount(src, item) or 0 end)
        end
        if (n or 0) == 0 then
            pcall(function()
                local it = exports.ak47_inventory:GetItemByName(src, item)
                n = it and (it.amount or it.count or 0) or 0
            end)
        end

    elseif inv == 'codem' then
        pcall(function() n = exports['codem-inventory']:GetItemsTotalAmount(src, item) or 0 end)

    elseif inv == 'core' then
        pcall(function()
            n = exports.core_inventory:getItemCount(src, 'default', item) or 0
        end)

    elseif inv == 'qb' then
        local p = fwPlayer(src)
        if p and p.Functions then
            pcall(function()
                local it = p.Functions.GetItemByName(item)
                n = it and (it.amount or it.count or 0) or 0
            end)
        end

    elseif inv == 'esx' then
        local p = fwPlayer(src)
        if p then
            pcall(function()
                local it = p.getInventoryItem(item)
                n = it and (it.count or 0) or 0
            end)
        end
    end

    return n or 0
end

